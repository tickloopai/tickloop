#!/usr/bin/env python3
"""Merge crates/agent integration test files into the single `all` test binary.

Idempotent: rerun it after a rebase brings new or changed top-level test files. It
- moves every `crates/agent/tests/*.rs` (and the `agent_console_pty/` submodules) into
  `crates/agent/tests/all/`, fixing relative `include_str!`/`include_bytes!` paths,
- replaces per-file `mod support;`-style declarations with references to the shared modules,
- rewrites self re-executions that pass a bare test name to `--exact` into `test_path!(..)`,
- regenerates `tests/all/main.rs` and keeps `crates/agent/Cargo.toml` at two test targets.

Usage: scripts/merge-agent-tests.py   (from anywhere; then `cargo fmt --all`)
"""

import re
import shutil
import sys
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent / "crates" / "agent"
TESTS = CRATE / "tests"
ALL = TESTS / "all"
MAIN = ALL / "main.rs"
MANIFEST = CRATE / "Cargo.toml"

SHARED_SUPPORT_MODULES = ("input_dialog", "provider_transport", "screen")
SUBDIRECTORY_MODULES = ("agent_console_pty",)
INCLUDE_MACRO = re.compile(r'(include_(?:str|bytes)!\(\s*")([^"]+)(")')

MAIN_HEADER = """\
//! Every crates/agent integration test, compiled as one binary.
//! Generated by scripts/merge-agent-tests.py; add a test file to this directory and rerun it.

#[path = "../model_http_support/mod.rs"]
mod model_http_support;
#[path = "../support/mod.rs"]
mod support;

/// The libtest name of a test function in this binary, for tests that re-execute themselves
/// with `--exact`; naming a function that does not exist fails to compile.
macro_rules! test_path {
    ($test:ident) => {{
        let _: fn() = $test;
        format!(
            "{}::{}",
            module_path!()
                .strip_prefix(concat!(env!("CARGO_CRATE_NAME"), "::"))
                .unwrap(),
            stringify!($test)
        )
    }};
}

"""

TEST_TARGETS = """\
[[test]]
name = "all"
path = "tests/all/main.rs"

[[test]]
name = "cli_fixture"
path = "tests/support/cli_fixture_main.rs"
harness = false
"""


def deepen_include_paths(source: str) -> str:
    return INCLUDE_MACRO.sub(lambda match: f"{match[1]}../{match[2]}{match[3]}", source)


def move_test_files() -> None:
    sources = sorted(TESTS.glob("*.rs"))
    for source in sources:
        if '#[path = "../src/' in source.read_text():
            sys.exit(f"{source} compiles crate sources itself; make it a unit test in src first")
        if (ALL / source.name).exists():
            sys.exit(f"{ALL / source.name} already exists; merge {source} by hand")
    ALL.mkdir(exist_ok=True)
    for source in sources:
        destination = ALL / source.name
        destination.write_text(deepen_include_paths(source.read_text()))
        source.unlink()
    for name in SUBDIRECTORY_MODULES:
        directory = TESTS / name
        if not directory.is_dir():
            continue
        target = ALL / name
        target.mkdir(exist_ok=True)
        for source in sorted(directory.glob("*.rs")):
            (target / source.name).write_text(deepen_include_paths(source.read_text()))
            source.unlink()
        shutil.rmtree(directory)


def reference_shared_modules(source: str) -> str:
    source = re.sub(
        r'#\[path = "support/mod\.rs"\]\s*\n\s*mod support;', "use crate::support;", source
    )
    for name in SHARED_SUPPORT_MODULES:
        source = re.sub(
            rf'#\[path = "support/{name}\.rs"\]\s*\n\s*mod {name};',
            f"use crate::support::{name};",
            source,
        )
        source = re.sub(
            rf'mod {name} \{{\s*include!\("(\.\./)*support/{name}\.rs"\);\s*\}}',
            f"use crate::support::{name};",
            source,
        )
    source = re.sub(r"(?m)^mod support;$", "use crate::support;", source)
    source = re.sub(r"(?m)^mod model_http_support;$", "use crate::model_http_support;", source)
    return source


def drop_submodule_paths(source: str, module: str) -> str:
    source = re.sub(rf'#\[path = "{module}/\w+\.rs"\]\s*\n(\s*mod \w+;)', r"\1", source)
    return re.sub(r"(?m)^(mod \w+;)\n\n(?=mod \w+;)", r"\1\n", source)


def name_reexecuted_tests(source: str) -> str:
    source = re.sub(
        r'"--exact",(\s*)"(\w+)"', r'"--exact",\1test_path!(\2).as_str()', source
    )
    source = re.sub(
        r'\.arg\("--exact"\)(\s*)\.arg\("(\w+)"\)', r'.arg("--exact")\1.arg(test_path!(\2))', source
    )
    # temp_storage passes the re-executed test's name through a shared helper.
    return re.sub(
        r'(assert_bash_uses_no_untrusted_root\(\s*)"(\w+)"', r"\1&test_path!(\2)", source
    )


def rewrite_test_sources() -> None:
    for path in sorted(ALL.rglob("*.rs")):
        if path == MAIN:
            continue
        source = path.read_text()
        rewritten = name_reexecuted_tests(reference_shared_modules(source))
        if path.parent == ALL and path.stem in SUBDIRECTORY_MODULES:
            rewritten = drop_submodule_paths(rewritten, path.stem)
        if rewritten != source:
            path.write_text(rewritten)


def write_main() -> None:
    modules = sorted(path.stem for path in ALL.glob("*.rs") if path != MAIN)
    MAIN.write_text(MAIN_HEADER + "".join(f"mod {module};\n" for module in modules))


def declare_test_targets() -> None:
    manifest = MANIFEST.read_text()
    if "autotests" not in manifest:
        manifest = manifest.replace("autobins = false\n", "autobins = false\nautotests = false\n", 1)
    manifest = re.sub(r"(?ms)^\[\[test\]\]\n.*?(?=^\[(?!\[test\]\]))", "", manifest)
    manifest = manifest.replace("[dependencies]\n", TEST_TARGETS + "\n[dependencies]\n", 1)
    MANIFEST.write_text(manifest)


def report_unnamed_reexecutions() -> None:
    leftovers = [
        f"{path.relative_to(CRATE)}:{number}"
        for path in sorted(ALL.rglob("*.rs"))
        for number, line in enumerate(path.read_text().splitlines(), 1)
        if re.search(r'"--exact"\s*[,)]\s*(\.arg\()?\s*"', line)
    ]
    if leftovers:
        sys.exit("re-executions still name a test by string: " + ", ".join(leftovers))


def main() -> None:
    move_test_files()
    rewrite_test_sources()
    write_main()
    declare_test_targets()
    report_unnamed_reexecutions()


if __name__ == "__main__":
    main()
